    if (일간오행 === 카드오행) return '비겁';
    if (상생[일간오행] === 카드오행) return '식상';
    if (상극[일간오행] === 카드오행) return '재성';
    if (상극[카드오행] === 일간오행) return '관성';
    if (상생[카드오행] === 일간오행) return '인성';
    return '비겁';
