  var 상생 = { 목: '화', 화: '토', 토: '금', 금: '수', 수: '목' };
  var 상극 = { 목: '토', 토: '수', 수: '화', 화: '금', 금: '목' };

  /** a에서 b로의 관계 */
  function 관계(a, b) {
    if (a === '태극' || b === '태극') return '태극';
    if (a === b) return '비견';
    if (상생[a] === b) return '상생';
    if (상극[a] === b) return '상극';
    if (상생[b] === a) return '역생';   // b가 a를 생함
    if (상극[b] === a) return '역극';   // b가 a를 극함
    return '무관';
  }

