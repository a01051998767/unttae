  // ── 덱 생성 ──────────────────────────────────────────────
  function buildDeck() {
    var deck = [];
    for (var i = 0; i < MAJOR.length; i++) {
      var m = MAJOR[i];
      deck.push({
        id: 'major-' + m[0],
        종류: '메이저',
        번호: m[0],
        이름: m[1],
        오행: m[2],
        음양: m[3],
        정: m[4],
        역: m[5],
        그림: m[6],
        설명: m[6]
      });
    }
    for (var s = 0; s < SUITS.length; s++) {
      var suit = SUITS[s];
      for (var r = 0; r < RANKS.length; r++) {
        var rank = RANKS[r];
        deck.push({
          id: suit.key + '-' + rank.n,
          종류: '마이너',
          수트: suit.name,
          수트키: suit.key,
          원소: suit.원소,
          번호: rank.n,
          이름: suit.name + ' ' + rank.name,
          오행: suit.오행,
          음양: rank.음양,
          정: rank.뜻 + ' — ' + SUIT_TONE[suit.key].정,
          역: rank.뜻 + ' — ' + SUIT_TONE[suit.key].역,
          주제: suit.주제,
          그림: MINOR_IMG[suit.key][r],
          설명: MINOR_IMG[suit.key][r] + ' ' + suit.한줄
        });
      }
    }
    return deck;
  }

